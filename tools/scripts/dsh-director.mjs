#!/usr/bin/env node
/**
 * Director launcher for the pinned official DeepSeek Harness (DSH) Web profile.
 *
 * Writes a thin overlay under `vendor/deepseek-harness/.director/` — the bundled
 * `@director/dsh-plugin-workbench` plugin plus a one-row `--patch` file — and then
 * launches the pinned `@deepseek-ai/dsh` release through `pnpm dlx`. DSH is never
 * forked or vendored: the overlay only inserts the Director plugin, so every DSH
 * built-in model tool (skill, todo_write, job_list/job_output/job_kill,
 * web_search/web_fetch, bash, read/write/edit/glob/grep, Code Mode
 * `tools.<name>({})`, subagent, workflow, goals, plan mode) comes straight from
 * the official release.
 *
 * The child process runs with the repository root as cwd so DSH discovers the
 * `.dsh/skills/director-workbench` skill (rank 100) by itself. Director
 * environment (`STAGE_GATEWAY_URL`, `DIRECTOR_GATEWAY_TOKEN`,
 * `DIRECTOR_TARGET_TOKEN`) is passed through when set, and `--no-open` is added
 * for headless runs (`CI` truthy or `DIRECTOR_DSH_NO_OPEN=1`).
 *
 * @module dsh-director
 */
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const dshRoot = resolve(repositoryRoot, "vendor/deepseek-harness");
const overlayDir = resolve(dshRoot, ".director");
const pluginPath = resolve(overlayDir, "plugin.mjs");
const patchPath = resolve(overlayDir, "cordis.yml");

/** Pinned official DSH release. The submodule ledger may lag; this pin wins. */
export const DSH_VERSION = "0.1.0-rc.6";

/** Director environment passed through to the DSH child process when set. */
export const DIRECTOR_ENV_PASSTHROUGH = Object.freeze([
  "STAGE_GATEWAY_URL",
  "DIRECTOR_GATEWAY_TOKEN",
  "DIRECTOR_TARGET_TOKEN",
  "DIRECTOR_SESSION_INSTRUCTIONS",
  "DIRECTOR_WORKSPACE_REFRESH_MS",
]);

/**
 * Render the `--patch` overlay for the official DSH web profile. The overlay is
 * intentionally a single insert row: DSH built-ins must stay untouched.
 * @param {string} bundledPluginPath - Absolute path of the bundled Director plugin.
 */
export function renderOverlayPatch(bundledPluginPath) {
  return `# Generated by tools/scripts/dsh-director.mjs — do not edit.
# Thin overlay for \`dsh web --patch\`: inserts only the Director workbench
# plugin. All DSH built-ins (skill, todo_write, job_*, web_search/web_fetch,
# bash, read/write/edit/glob/grep, Code Mode, subagent, workflow, goals, plan
# mode) stay as shipped in the pinned official release (${DSH_VERSION}).
- insert:
    - id: director-workbench
      name: ${JSON.stringify(bundledPluginPath)}
`;
}

/**
 * Whether the launcher should ask DSH Web not to open a browser.
 * Headless/cloud runs set `CI=1` (or `CI=true`) or `DIRECTOR_DSH_NO_OPEN=1`.
 * @param {NodeJS.ProcessEnv} env
 */
export function shouldSkipBrowserOpen(env = process.env) {
  const isEnabled = (value) => typeof value === "string" && ["1", "true", "yes"].includes(value.trim().toLowerCase());
  return isEnabled(env.CI) || isEnabled(env.DIRECTOR_DSH_NO_OPEN);
}

/**
 * Build the `pnpm dlx` argument list that launches the pinned DSH Web profile.
 * @param {string} overlayPatchPath - Absolute path of the generated cordis.yml.
 * @param {NodeJS.ProcessEnv} env
 */
export function buildDshWebArgs(overlayPatchPath, env = process.env) {
  const args = [`--package=@deepseek-ai/dsh@${DSH_VERSION}`, "dlx", "dsh", "web", "--patch", overlayPatchPath];
  if (shouldSkipBrowserOpen(env)) args.push("--no-open");
  return args;
}

/**
 * Collect the Director variables that must reach the DSH child process.
 * Unset or blank variables are omitted so DSH falls back to its own defaults.
 * @param {NodeJS.ProcessEnv} env
 * @returns {Record<string, string>}
 */
export function collectDirectorEnv(env = process.env) {
  const passed = {};
  for (const key of DIRECTOR_ENV_PASSTHROUGH) {
    const value = env[key];
    if (typeof value === "string" && value.trim() !== "") passed[key] = value;
  }
  return passed;
}

function git(args, cwd = repositoryRoot) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

/** Initialize the submodule when needed and write the Director overlay. */
function prepareOverlay() {
  if (!existsSync(resolve(dshRoot, "package.json"))) {
    git(["submodule", "update", "--init", "--depth", "1", "vendor/deepseek-harness"]);
  }
  mkdirSync(overlayDir, { recursive: true });
  execFileSync(
    resolve(repositoryRoot, "node_modules/.bin/esbuild"),
    [
      resolve(repositoryRoot, "packages/dsh-plugin-workbench/src/cordis.ts"),
      "--bundle",
      "--platform=node",
      "--format=esm",
      "--target=node22",
      `--outfile=${pluginPath}`,
    ],
    { cwd: repositoryRoot, stdio: "inherit" },
  );
  writeFileSync(patchPath, renderOverlayPatch(pluginPath));
}

function main() {
  prepareOverlay();
  console.log(`DeepSeek Harness overlay written to ${overlayDir}`);
  if (process.argv.includes("--prepare-only")) process.exit(0);

  const directorEnv = collectDirectorEnv(process.env);
  const passedKeys = Object.keys(directorEnv);
  if (passedKeys.length > 0) console.log(`Passing through Director env: ${passedKeys.join(", ")}`);
  const args = buildDshWebArgs(patchPath, process.env);
  if (args.includes("--no-open")) console.log("Headless run detected (CI/DIRECTOR_DSH_NO_OPEN): passing --no-open");

  console.log(`Starting Director DeepSeek Harness ${DSH_VERSION} at http://127.0.0.1:3080`);
  // cwd must stay the repository root: DSH discovers `<git-root>/.dsh/skills`
  // (director-workbench, rank 100) relative to its working directory.
  const launched = spawnSync("pnpm", args, {
    cwd: repositoryRoot,
    stdio: "inherit",
    env: { ...process.env, ...directorEnv },
  });
  if (launched.error) {
    if (launched.error.code === "ENOENT") {
      console.error(
        "error: pnpm was not found on PATH. Install pnpm (https://pnpm.io/installation), then rerun `npm run dsh`.",
      );
      process.exit(1);
    }
    throw launched.error;
  }
  if (launched.signal) process.kill(process.pid, launched.signal);
  if (launched.status !== 0) {
    console.error(
      `error: DeepSeek Harness ${DSH_VERSION} exited with status ${launched.status}. ` +
        "Check the output above; the Gateway must be running (`npm run dev:gateway`) for Director tools to work.",
    );
  }
  process.exit(launched.status ?? 0);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) main();
